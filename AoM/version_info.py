"""Runtime build/version information for the Options -> Tools -> About screen.

Collects the build stamp (git short hash + build time), the Python runtime, and
key package versions so a player/developer can tell which build they are looking
at. Web builds read the stamp baked in by ``scripts/write-build-info.py``;
native runs fall back to reading git at runtime.
"""

from __future__ import annotations

import sys

# Package version lookups are best-effort: any of these may be absent in a
# given runtime (e.g. the Pygbag wasm bundle ships a trimmed stdlib).
_PACKAGE_NAMES = ("pygame-ce",)


def _git(args):
    try:
        import subprocess

        root = _repo_root()
        if root is None:
            return ""
        out = subprocess.check_output(
            ["git", *args], cwd=str(root), stderr=subprocess.DEVNULL
        )
        return out.decode("utf-8", "replace").strip()
    except Exception:
        return ""


def _repo_root():
    try:
        from pathlib import Path

        return Path(__file__).resolve().parent.parent
    except Exception:
        return None


def build_stamp():
    """Return ``(hash, built_at)`` for this build, or ``("unknown", "unknown")``.

    Prefers the generated ``build_info`` module (present in packaged/web
    builds), then falls back to live git metadata (native checkouts).
    """
    try:
        import build_info  # type: ignore  # generated by scripts/write-build-info.py

        build_hash = str(getattr(build_info, "BUILD_HASH", "") or "").strip()
        build_time = str(getattr(build_info, "BUILD_TIME", "") or "").strip()
        if build_hash or build_time:
            return (build_hash or "unknown", build_time or "unknown")
    except Exception:
        pass

    build_hash = _git(["rev-parse", "--short=12", "HEAD"])
    build_time = _git(["show", "-s", "--format=%cI", "HEAD"])
    return (build_hash or "unknown", build_time or "unknown")


def python_runtime():
    implementation = getattr(sys, "implementation", None)
    name = getattr(implementation, "name", "python")
    version = "%d.%d.%d" % sys.version_info[:3]
    return f"{name} {version}"


def _package_version(*names):
    try:
        from importlib import metadata
    except Exception:
        return "-"
    for name in names:
        try:
            return metadata.version(name)
        except Exception:
            continue
    return "-"


def package_versions():
    """Return a list of ``(label, version)`` rows for key packages."""
    rows = []
    try:
        import pygame

        rows.append(("pygame", str(getattr(pygame.version, "ver", "?"))))
        sdl = getattr(pygame.version, "SDL", None)
        if sdl:
            rows.append(("SDL", ".".join(str(part) for part in sdl)))
    except Exception:
        rows.append(("pygame", "-"))

    seen = {label for label, _ in rows}
    for name in _PACKAGE_NAMES:
        if name in seen:
            continue
        rows.append((name, _package_version(name)))
    return rows


def about_lines():
    """Rows for the About screen: ``[(label, value), ...]``."""
    build_hash, build_time = build_stamp()
    rows = [
        ("Build", build_hash),
        ("Built", build_time),
        ("Python", python_runtime()),
        ("Platform", sys.platform),
    ]
    rows.extend(package_versions())
    return rows
